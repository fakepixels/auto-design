import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import pc from "picocolors";

/**
 * `auto-design add <system>`: install a design system into any Tailwind v4
 * app, from a local system repo or a hosted registry. It does what the shadcn
 * base item does, plus the parts shadcn's merge can't: the theme lock as its
 * own file, imported straight after Tailwind.
 */

type RegistryFile = { path: string; type: string; target?: string; content?: string };
type RegistryItem = { name: string; type: string; dependencies?: string[]; files?: RegistryFile[]; docs?: string; meta?: { requires?: string[] } };

export interface AddOptions {
  source: string;
  cwd: string;
  components: string[];
  install: boolean;
  /** Register the auto-design MCP server for coding agents (default true). */
  mcp?: boolean;
}

const SKIP = new Set(["node_modules", ".next", ".git", "dist", "build", ".turbo", ".vercel", ".svelte-kit", ".output"]);

function walk(dir: string, depth: number, visit: (file: string) => boolean | void): boolean {
  if (depth > 5) return false;
  let entries: string[];
  try {
    entries = readdirSync(dir).sort();
  } catch {
    return false;
  }
  for (const e of entries) {
    if (SKIP.has(e) || e.startsWith(".")) continue;
    const full = join(dir, e);
    let st;
    try {
      st = statSync(full);
    } catch {
      continue;
    }
    if (st.isDirectory()) {
      if (walk(full, depth + 1, visit)) return true;
    } else if (visit(full) === true) return true;
  }
  return false;
}

const TAILWIND_IMPORT = /@import\s+["']tailwindcss["'][^;]*;/;

/** The app's Tailwind v4 entry: the CSS file that imports "tailwindcss". */
export function findTailwindEntry(app: string): string | null {
  const preferred = ["app/globals.css", "src/app/globals.css", "src/index.css", "src/styles.css", "src/app.css", "styles/globals.css", "app/app.css"];
  for (const p of preferred) {
    const full = join(app, p);
    if (existsSync(full) && TAILWIND_IMPORT.test(readFileSync(full, "utf8"))) return full;
  }
  let found: string | null = null;
  walk(app, 0, (f) => {
    if (f.endsWith(".css") && TAILWIND_IMPORT.test(readFileSync(f, "utf8"))) {
      found = f;
      return true;
    }
  });
  return found;
}

/** Add `@import "./auto-design.css";` right after the Tailwind import, once. */
export function insertImport(css: string): string {
  if (/@import\s+["']\.\/auto-design\.css["']/.test(css)) return css;
  return css.replace(TAILWIND_IMPORT, (m) => `${m}\n@import "./auto-design.css";`);
}

const AGENT_POINTER = `
## Design system

This app uses a design system generated by auto-design. Read DESIGN.md before writing or changing any UI,
and run \`npx auto-design check\` after every change. Off-system classes don't compile.
The \`auto-design\` MCP server (\`npx auto-design mcp\`) answers the same questions as tools: rules, tokens,
components, and checks for code and text messages.
`;

/** Point coding agents at DESIGN.md from whichever instruction files the app has. */
export function pointAgents(app: string): string[] {
  const touched: string[] = [];
  const files = ["AGENTS.md", "CLAUDE.md"].map((f) => join(app, f)).filter(existsSync);
  if (!files.length) files.push(join(app, "AGENTS.md"));
  for (const f of files) {
    const current = existsSync(f) ? readFileSync(f, "utf8") : "";
    if (current.includes("DESIGN.md")) continue;
    writeFileSync(f, current ? current.trimEnd() + "\n" + AGENT_POINTER : `# Agent instructions\n${AGENT_POINTER}`);
    touched.push(f);
  }
  return touched;
}

/**
 * Register the design system's MCP server with coding agents that read
 * project config: .mcp.json (Claude Code and others) and .cursor/mcp.json
 * when the project uses Cursor. Existing servers are kept.
 */
export function registerMcp(app: string): string[] {
  const touched: string[] = [];
  const entry = { command: "npx", args: ["auto-design", "mcp"] };
  const targets = [join(app, ".mcp.json")];
  if (existsSync(join(app, ".cursor"))) targets.push(join(app, ".cursor", "mcp.json"));
  for (const path of targets) {
    let json: { mcpServers?: Record<string, unknown> } = {};
    if (existsSync(path)) {
      try {
        json = JSON.parse(readFileSync(path, "utf8"));
      } catch {
        continue; // Not ours to repair.
      }
    }
    if (json.mcpServers?.["auto-design"]) continue;
    json.mcpServers = { ...(json.mcpServers ?? {}), "auto-design": entry };
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, JSON.stringify(json, null, 2) + "\n");
    touched.push(path);
  }
  return touched;
}

/** Where shadcn-style components live in this app. */
function componentsDir(app: string): { ui: string; lib: string } {
  const src = existsSync(join(app, "src"));
  const base = src ? join(app, "src") : app;
  const cfgPath = join(app, "components.json");
  if (existsSync(cfgPath)) {
    try {
      const cfg = JSON.parse(readFileSync(cfgPath, "utf8"));
      const toPath = (alias: string | undefined, fallback: string) =>
        alias?.startsWith("@/") ? join(base, alias.slice(2)) : join(base, fallback);
      return { ui: toPath(cfg.aliases?.ui, "components/ui"), lib: toPath(cfg.aliases?.lib, "lib") };
    } catch {
      /* fall through */
    }
  }
  return { ui: join(base, "components/ui"), lib: join(base, "lib") };
}

const UTILS = `import { clsx, type ClassValue } from "clsx";
import { twMerge } from "tailwind-merge";

export function cn(...inputs: ClassValue[]) {
  return twMerge(clsx(inputs));
}
`;

/** Import the font packages once, in the app's root entry, when we can find it. */
function addFontImports(app: string, packages: string[]): { path: string; changed: boolean } | null {
  const entries = ["app/layout.tsx", "app/layout.jsx", "src/app/layout.tsx", "src/app/layout.jsx", "src/main.tsx", "src/main.jsx", "pages/_app.tsx", "pages/_app.jsx", "app/root.tsx", "src/routes/__root.tsx"];
  for (const e of entries) {
    const full = join(app, e);
    if (!existsSync(full)) continue;
    let src = readFileSync(full, "utf8");
    const missing = packages.filter((p) => !src.includes(`"${p}"`) && !src.includes(`'${p}'`));
    if (!missing.length) return { path: full, changed: false };
    const lines = src.split("\n");
    let last = -1;
    lines.forEach((l, i) => {
      if (/^import\s/.test(l)) last = i;
    });
    lines.splice(last + 1, 0, ...missing.map((p) => `import "${p}";`));
    src = lines.join("\n");
    writeFileSync(full, src);
    return { path: full, changed: true };
  }
  return null;
}

function packageManager(app: string): { name: string; add: string[] } {
  if (existsSync(join(app, "pnpm-lock.yaml"))) return { name: "pnpm", add: ["add"] };
  if (existsSync(join(app, "yarn.lock"))) return { name: "yarn", add: ["add"] };
  if (existsSync(join(app, "bun.lockb")) || existsSync(join(app, "bun.lock"))) return { name: "bun", add: ["add"] };
  return { name: "npm", add: ["install"] };
}

export async function loadItem(source: string, name: string): Promise<RegistryItem> {
  if (/^https?:\/\//.test(source)) {
    const base = source.endsWith(".json") ? source.replace(/[^/]+\.json$/, "") : source.replace(/\/?$/, "/");
    const res = await fetch(`${base}${name}.json`, { headers: authHeaders() });
    if (!res.ok) throw new Error(`Couldn't fetch ${base}${name}.json (${res.status})`);
    return (await res.json()) as RegistryItem;
  }
  const root = resolve(source);
  const path = existsSync(join(root, "public/r")) ? join(root, "public/r", `${name}.json`) : join(root, `${name}.json`);
  if (!existsSync(path)) throw new Error(`No registry item "${name}" at ${path}. Point add at a system repo or its /r/ URL.`);
  return JSON.parse(readFileSync(path, "utf8")) as RegistryItem;
}

/** Private registries (the token-protected server auto-design can deploy) read a bearer token from the environment. */
function authHeaders(): Record<string, string> {
  const token = process.env.AUTO_DESIGN_TOKEN ?? process.env.REGISTRY_TOKEN;
  return token ? { authorization: `Bearer ${token}` } : {};
}

export async function listComponents(source: string): Promise<string[]> {
  if (/^https?:\/\//.test(source)) {
    const base = source.endsWith(".json") ? source.replace(/[^/]+\.json$/, "") : source.replace(/\/?$/, "/");
    try {
      const res = await fetch(`${base}registry.json`, { headers: authHeaders() });
      if (!res.ok) return [];
      const index = (await res.json()) as { items?: { name: string; type: string }[] };
      return (index.items ?? []).filter((i) => i.type === "registry:ui" || i.type === "registry:lib").map((i) => i.name);
    } catch {
      return [];
    }
  }
  const dir = join(resolve(source), "public/r");
  return existsSync(dir)
    ? readdirSync(dir)
        .filter((f) => f.endsWith(".json") && f !== "base.json" && f !== "registry.json")
        .map((f) => f.replace(/\.json$/, ""))
    : [];
}

export async function runAdd(opts: AddOptions) {
  const app = resolve(opts.cwd);
  const rel = (p: string) => relative(process.cwd(), p) || ".";
  const entry = findTailwindEntry(app);
  if (!entry) {
    throw new Error(
      `No Tailwind v4 CSS entry in ${rel(app)}. auto-design needs a CSS file with @import "tailwindcss"; set up Tailwind v4 first.`,
    );
  }

  const base = await loadItem(opts.source, "base");
  const file = (p: string) => base.files?.find((f) => f.path === p)?.content;
  const css = file("css/auto-design.css");
  if (!css) throw new Error("The base item has no css/auto-design.css. Rebuild the system with a current auto-design.");

  const written: string[] = [];
  const cssTarget = join(dirname(entry), "auto-design.css");
  writeFileSync(cssTarget, css);
  written.push(cssTarget);
  const entrySrc = readFileSync(entry, "utf8");
  const withImport = insertImport(entrySrc);
  if (withImport !== entrySrc) {
    writeFileSync(entry, withImport);
    written.push(entry);
  }
  const designMd = file("DESIGN.md");
  if (designMd) {
    writeFileSync(join(app, "DESIGN.md"), designMd);
    written.push(join(app, "DESIGN.md"));
  }
  const guard = file("rules/guardrails.json");
  if (guard) {
    // Remember where the system came from, so agent tools can fetch components the app hasn't installed yet.
    const registry = /^https?:\/\//.test(opts.source) ? opts.source : relative(app, resolve(opts.source)) || ".";
    const json = { ...JSON.parse(guard), registry };
    writeFileSync(join(app, "auto-design.json"), JSON.stringify(json, null, 2) + "\n");
    written.push(join(app, "auto-design.json"));
  }
  written.push(...pointAgents(app));
  if (opts.mcp !== false) written.push(...registerMcp(app));
  // Review screenshots and reports are local output, not source.
  const gitignore = join(app, ".gitignore");
  if (existsSync(gitignore) && !/^\/?\.auto-design\/?$/m.test(readFileSync(gitignore, "utf8"))) {
    writeFileSync(gitignore, readFileSync(gitignore, "utf8").trimEnd() + "\n\n# auto-design review output\n.auto-design/\n");
    written.push(gitignore);
  }

  const deps = new Set(base.dependencies ?? []);
  const fontPackages = [...deps].filter((d) => d.startsWith("@fontsource"));

  let names = opts.components;
  if (names.length === 1 && names[0] === "all") names = await listComponents(opts.source);
  if (names.length) {
    const queue = [...names];
    const seen = new Set<string>();
    names = [];
    while (queue.length) {
      const n = queue.shift()!;
      if (seen.has(n)) continue;
      seen.add(n);
      names.push(n);
    }
    const dirs = componentsDir(app);
    const utilsPath = join(dirs.lib, "utils.ts");
    if (!existsSync(utilsPath) && !existsSync(join(dirs.lib, "utils.js"))) {
      mkdirSync(dirs.lib, { recursive: true });
      writeFileSync(utilsPath, UTILS);
      written.push(utilsPath);
    }
    for (let i = 0; i < names.length; i++) {
      const item = await loadItem(opts.source, names[i]!);
      // In-system dependencies (an approval card needs the button) come along.
      for (const r of item.meta?.requires ?? []) if (!names.includes(r)) names.push(r);
      for (const d of item.dependencies ?? []) deps.add(d);
      for (const f of item.files ?? []) {
        if (!f.content) continue;
        const target = join(f.type === "registry:lib" ? dirs.lib : dirs.ui, f.path.split("/").pop()!);
        mkdirSync(dirname(target), { recursive: true });
        writeFileSync(target, f.content);
        written.push(target);
      }
    }
  }

  const fontEntry = addFontImports(app, fontPackages);
  if (fontEntry?.changed) written.push(fontEntry.path);

  console.log(`${pc.green("✓")} Installed the design system into ${rel(app)}`);
  for (const w of [...new Set(written)]) console.log(`  ${pc.dim(rel(w))}`);

  const pm = packageManager(app);
  const depList = [...deps];
  if (depList.length) {
    const cmd = [pm.name, ...pm.add, ...depList];
    if (opts.install) {
      console.log(`${pc.dim("$")} ${cmd.join(" ")}`);
      const r = spawnSync(cmd[0]!, cmd.slice(1), { cwd: app, stdio: "inherit", shell: process.platform === "win32" });
      if (r.status !== 0) console.log(`${pc.yellow("!")} Install failed; run it yourself: ${cmd.join(" ")}`);
    } else {
      console.log(`\nInstall the dependencies: ${pc.cyan(cmd.join(" "))}`);
    }
  }
  if (fontPackages.length && !fontEntry) {
    console.log(`\nImport the fonts once in your app's root file:\n${fontPackages.map((p) => `  import "${p}";`).join("\n")}`);
  }
  console.log(`\nThen run ${pc.cyan("npx auto-design check")}. Leftover template colors and theme keys in your CSS will show up as errors.`);
}
