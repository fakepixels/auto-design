import { bezier } from "../scales.js";
import type { DesignSystem } from "../system.js";
import { motionLanguage } from "./language.js";

/**
 * The system's motion as a TypeScript module for apps: durations, easing,
 * springs and ready-made presets for Motion (motion.dev, MIT) or the Web
 * Animations API. Agents writing animated UI import these instead of
 * inventing numbers.
 */
export function motionModule(s: DesignSystem): string {
  const m = s.motion;
  const lang = motionLanguage(s);
  const sec = (ms: number) => +(ms / 1000).toFixed(3);
  const arr = (b: readonly number[]) => `[${b.join(", ")}]`;
  const spring = m.spring && m.spring.bounce > 0 ? `{ type: "spring", duration: ${m.spring.duration}, bounce: ${m.spring.bounce} } as const` : m.spring ? `{ type: "spring", duration: ${m.spring.duration}, bounce: 0 } as const` : "null";
  return `// @generated by auto-design from design.config.ts. The ${s.config.displayName} motion profile (${m.name}).
// Use with Motion (import { motion } from "motion/react") or element.animate(). Durations are in seconds.

export const duration = { fast: ${sec(m.durations.fast)}, base: ${sec(m.durations.base)}, slow: ${sec(m.durations.slow)}, reveal: ${sec(m.reveal)} } as const;

export const ease = { out: ${arr(m.easing.out)}, inOut: ${arr(m.easing.inOut)} } as const;

/** The same curves as CSS strings, for element.animate() and inline styles. */
export const css = {
  easeOut: "${bezier(m.easing.out)}",
  easeInOut: "${bezier(m.easing.inOut)}",
  spring: "${lang.spring}",
} as const;

/** For drag, layout changes and anything that follows the pointer.${m.spring ? "" : " This profile has none: use ease.out."} */
export const spring = ${spring};

/** Entering elements: a fade${m.enterScale < 1 ? ` from scale ${m.enterScale}` : ""}${m.enterDistance ? ` with ${m.enterDistance}px of travel` : ""}. Never from scale 0. */
export const enter = {
  initial: { opacity: 0${m.enterScale < 1 ? `, scale: ${m.enterScale}` : ""}${m.enterDistance ? `, y: ${m.enterDistance}` : ""} },
  animate: { opacity: 1${m.enterScale < 1 ? ", scale: 1" : ""}${m.enterDistance ? ", y: 0" : ""} },
  transition: { duration: duration.base, ease: ease.out },
} as const;

export const exit = {
  opacity: 0${m.enterScale < 1 ? `, scale: ${m.enterScale}` : ""},
  transition: { duration: duration.fast, ease: ease.inOut },
} as const;

/** Content arriving as it scrolls into view: data, sections, text. Never a response to a press. */
export const reveal = {
  initial: { opacity: 0${m.revealDistance ? `, y: ${m.revealDistance}` : ""} },
  whileInView: { opacity: 1${m.revealDistance ? ", y: 0" : ""} },
  viewport: { once: true, amount: 0.4 },
  transition: { duration: duration.reveal, ease: ease.out },
} as const;

/** Seconds between items in a staggered reveal. */
export const stagger = ${sec(m.stagger)};

/** Brand animation timing (launch films, social posts): slower and larger than product UI. */
export const brand = { beat: ${sec(lang.beat)}, stagger: ${sec(lang.stagger)}, hold: ${sec(lang.hold)}, travel: ${lang.travel} } as const;

/** Whether loops (spinners aside) may move at all. */
export const ambient = ${m.ambient};
`;
}
