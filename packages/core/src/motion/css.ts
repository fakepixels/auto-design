import { rootTokens } from "../emit/css.js";
import { fontStack } from "../emit/shared.js";
import { shadowCss } from "../scales.js";
import type { DesignSystem } from "../system.js";
import { motionLanguage } from "./language.js";

/**
 * The stylesheet every brand animation shares. Sizes are in stage units
 * (`--u`, 1% of the stage's short side), so a scene renders the same at
 * 320px in a gallery and at 1080p in a video. Timing is CSS animation with
 * per-element delays; the runtime pauses every animation and drives one
 * clock, so playback, scrubbing and video frames all show the same thing.
 */
export function motionCss(s: DesignSystem): string {
  const lang = motionLanguage(s);
  const sans = fontStack(s.type.fonts.sans);
  const display = s.type.fonts.display ? fontStack(s.type.fonts.display) : sans;
  const mono = fontStack(s.type.fonts.mono);
  const displayWeight = Math.max(...(s.type.fonts.display ?? s.type.fonts.sans).weights);
  const strong = Math.max(...s.type.fonts.sans.weights);
  const medium = s.type.fonts.sans.weights.find((w) => w >= 500) ?? strong;
  const radius = s.config.shape.radius;
  const texture = s.config.texture;
  const vars = (mode: "light" | "dark") =>
    Object.entries(rootTokens(s, mode))
      .map(([k, v]) => `${k}: ${v};`)
      .join(" ");

  const card = {
    minimal: `background: var(--card); border: calc(var(--px) * 1) solid var(--border); box-shadow: ${shadowCss(s.shadows.sm)};`,
    editorial: `background: var(--card); border: 0; box-shadow: none;`,
    glass: `background: color-mix(in oklab, var(--card) 72%, transparent); border: calc(var(--px) * 1) solid color-mix(in oklab, var(--foreground) 10%, transparent); box-shadow: ${shadowCss(s.shadows.lg)}; backdrop-filter: blur(calc(var(--u) * 2)); -webkit-backdrop-filter: blur(calc(var(--u) * 2));`,
    tactile: `background: var(--card); border: 0; box-shadow: ${shadowCss(s.shadows.lg)};`,
    technical: `background: var(--card); border: calc(var(--px) * 1) solid var(--border); box-shadow: none;`,
  }[texture];

  const backdrop = {
    minimal: "none",
    editorial: "none",
    glass: `radial-gradient(60% 60% at 18% 22%, color-mix(in oklab, var(--primary) 26%, transparent), transparent 70%), radial-gradient(55% 55% at 82% 78%, color-mix(in oklab, var(--chart-2) 24%, transparent), transparent 70%)`,
    tactile: "none",
    technical: `linear-gradient(to right, color-mix(in oklab, var(--border) 70%, transparent) calc(var(--px) * 1), transparent 0) 0 0 / calc(var(--u) * 8) calc(var(--u) * 8), linear-gradient(to bottom, color-mix(in oklab, var(--border) 70%, transparent) calc(var(--px) * 1), transparent 0) 0 0 / calc(var(--u) * 8) calc(var(--u) * 8)`,
  }[texture];

  return `/* Brand animations for ${s.config.displayName}. @generated by auto-design from design.config.ts. */
.adm-stage {
  --beat: ${lang.beat}ms; --stagger: ${lang.stagger}ms; --ease: ${lang.ease}; --ease-in-out: ${lang.easeInOut}; --spring: ${lang.spring};
  --travel: ${lang.travel}; --scale-from: ${lang.scaleFrom}; --pop-from: ${lang.popFrom};
  position: relative; overflow: hidden; container-type: size; isolation: isolate;
  background: ${texture === "tactile" ? "var(--muted)" : "var(--background)"}; color: var(--foreground);
  font-family: ${sans}; font-feature-settings: "ss01", "cv11"; -webkit-font-smoothing: antialiased; text-rendering: optimizeLegibility;
}
.adm-stage.adm-light { ${vars("light")} }
.adm-stage.adm-dark { ${vars("dark")} }
.adm-stage *, .adm-stage *::before, .adm-stage *::after { box-sizing: border-box; margin: 0; }
.adm-frame { position: absolute; inset: 0; --u: 1cqmin; --px: calc(var(--u) * 0.2); }
.adm-backdrop { position: absolute; inset: 0; background: ${backdrop}; pointer-events: none; }
.adm-scene { position: absolute; inset: 0; display: flex; flex-direction: column; align-items: center; justify-content: center; padding: calc(var(--u) * 9); text-align: center; }
.adm-scene.adm-left { align-items: flex-start; text-align: left; }
.adm-display { font-family: ${display}; font-weight: ${displayWeight}; letter-spacing: -0.025em; line-height: 1.04; text-wrap: balance; }
.adm-strong { font-weight: ${strong}; }
.adm-medium { font-weight: ${medium}; }
.adm-mono { font-family: ${mono}; }
.adm-muted { color: var(--muted-foreground); }
.adm-num { font-variant-numeric: tabular-nums; }
.adm-card { ${card} border-radius: calc(var(--px) * ${radius + 4}); }
.adm-mark { display: grid; place-items: center; width: calc(var(--u) * 12); height: calc(var(--u) * 12); border-radius: calc(var(--px) * ${Math.max(radius * 2, 8)}); background: var(--primary); color: var(--primary-foreground); font-weight: ${strong}; font-size: calc(var(--u) * 6); line-height: 1; flex: none; }
.adm-button { display: inline-flex; align-items: center; justify-content: center; height: calc(var(--u) * 6.4); padding: 0 calc(var(--u) * 3); border-radius: calc(var(--px) * ${radius}); background: var(--primary); color: var(--primary-foreground); font-weight: ${medium}; font-size: calc(var(--u) * 2.5); white-space: nowrap; position: relative; }
.adm-button.adm-outline { background: transparent; color: var(--foreground); box-shadow: inset 0 0 0 calc(var(--px) * 1.5) var(--border); }
.adm-badge { display: inline-flex; align-items: center; gap: calc(var(--u) * 0.8); height: calc(var(--u) * 3.2); padding: 0 calc(var(--u) * 1.3); border-radius: 999px; font-size: calc(var(--u) * 1.7); font-weight: ${medium}; white-space: nowrap; }
.adm-badge::before { content: ""; width: calc(var(--u) * 0.9); height: calc(var(--u) * 0.9); border-radius: 50%; background: currentColor; }
.adm-badge.adm-ok { background: color-mix(in oklab, var(--success) 16%, transparent); color: color-mix(in oklab, var(--success) 60%, var(--foreground)); }
.adm-badge.adm-warn { background: color-mix(in oklab, var(--warning) 22%, transparent); color: color-mix(in oklab, var(--warning) 45%, var(--foreground)); }

/* Timing: every animated element waits for its scene (--t0) plus its own delay (--d). */
.adm-in, .adm-fade, .adm-pop, .adm-wipe, .adm-rise, .adm-grow, .adm-draw, .adm-hide, .adm-show, .adm-press, .adm-glide {
  animation-delay: calc(var(--t0, 0ms) + var(--d, 0ms)); animation-fill-mode: both; animation-duration: var(--beat); animation-timing-function: var(--ease);
}
.adm-in { animation-name: adm-in; }
.adm-fade { animation-name: adm-fade; }
.adm-pop { animation-name: adm-pop; animation-timing-function: var(--spring); }
.adm-wipe { animation-name: adm-wipe; animation-timing-function: var(--ease-in-out); }
.adm-rise { animation-name: adm-rise; }
.adm-grow { animation-name: adm-grow; animation-timing-function: var(--ease-in-out); }
.adm-draw { animation-name: adm-draw; animation-duration: calc(var(--beat) * 2); animation-timing-function: var(--ease-in-out); stroke-dasharray: 1; }
.adm-hide { animation-name: adm-hide; animation-duration: 1ms; }
.adm-show { animation-name: adm-show; animation-duration: calc(var(--beat) * 0.5); }
.adm-press { animation-name: adm-press; animation-duration: 260ms; animation-timing-function: var(--ease-in-out); }
.adm-glide { animation-name: adm-glide; animation-duration: calc(var(--beat) * 1.4); animation-timing-function: var(--ease-in-out); }
/* Scenes in a sequence fade on their own delay (--sd), so it never leaks into the elements inside. */
.adm-scene-in, .adm-scene-out { animation-delay: calc(var(--t0, 0ms) + var(--sd, 0ms)); animation-fill-mode: both; animation-duration: ${lang.crossfade}ms; animation-timing-function: var(--ease-in-out); }
.adm-scene-in { animation-name: adm-fade; }
.adm-scene-out { animation-name: adm-out; }
.adm-word { display: inline-block; white-space: pre; }
.adm-clip { display: inline-block; overflow: hidden; vertical-align: bottom; padding-bottom: 0.08em; }
@keyframes adm-in { from { opacity: 0; transform: translateY(calc(var(--travel) * var(--u))) scale(var(--scale-from)); } to { opacity: 1; transform: none; } }
@keyframes adm-fade { from { opacity: 0; } to { opacity: 1; } }
@keyframes adm-out { from { opacity: 1; } to { opacity: 0; } }
@keyframes adm-pop { from { opacity: 0; transform: scale(var(--pop-from)); } to { opacity: 1; transform: none; } }
@keyframes adm-wipe { from { clip-path: inset(0 100% 0 0); } to { clip-path: inset(0 0 0 0); } }
${lang.travel ? "@keyframes adm-rise { from { transform: translateY(105%); } to { transform: none; } }" : "@keyframes adm-rise { from { opacity: 0; } to { opacity: 1; } }"}
@keyframes adm-grow { from { clip-path: inset(100% 0 0 0); } to { clip-path: inset(0 0 0 0); } }
@keyframes adm-draw { from { stroke-dashoffset: 1; } to { stroke-dashoffset: 0; } }
@keyframes adm-hide { to { opacity: 0; visibility: hidden; } }
@keyframes adm-show { from { opacity: 0; } to { opacity: 1; } }
@keyframes adm-press { 0% { transform: none; } 45% { transform: scale(0.95); } 100% { transform: none; } }
@keyframes adm-glide { from { transform: translate(calc(var(--fx) * var(--u)), calc(var(--fy) * var(--u))); opacity: 0; } 15% { opacity: 1; } to { transform: none; opacity: 1; } }
.adm-spin { animation: adm-spin 900ms linear infinite; animation-delay: calc(var(--t0, 0ms) + var(--d, 0ms)); }
@keyframes adm-spin { to { transform: rotate(1turn); } }
.adm-dots i { display: inline-block; width: calc(var(--u) * 1.1); height: calc(var(--u) * 1.1); margin: 0 calc(var(--u) * 0.35); border-radius: 50%; background: var(--muted-foreground); animation: adm-blink 1200ms var(--ease-in-out) infinite both; }
.adm-dots i:nth-child(2) { animation-delay: 160ms; }
.adm-dots i:nth-child(3) { animation-delay: 320ms; }
@keyframes adm-blink { 0%, 100% { opacity: 0.25; } 40% { opacity: 1; } }
.adm-cursor { position: absolute; width: calc(var(--u) * 3.4); height: calc(var(--u) * 3.4); pointer-events: none; z-index: 5; filter: drop-shadow(0 calc(var(--px) * 2) calc(var(--px) * 4) oklch(0 0 0 / 0.25)); }
.adm-loop { animation: adm-loop 1600ms var(--ease-in-out) infinite both; transform-origin: left; }
@keyframes adm-loop { 0% { transform: scaleX(0.02); } 70% { transform: scaleX(1); opacity: 1; } 100% { transform: scaleX(1); opacity: 0; } }
${lang.ambient ? "" : ".adm-spin, .adm-dots i, .adm-loop { animation: none; }"}
`;
}
