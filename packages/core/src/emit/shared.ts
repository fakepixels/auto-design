import type { FontConfig } from "../schema.js";
import type { DesignSystem } from "../system.js";

export const GENERATOR = "auto-design 0.1.0";

export const WEIGHT_NAMES: Record<number, string> = {
  300: "light",
  400: "normal",
  500: "medium",
  600: "semibold",
  700: "bold",
};

export function fontStack(font: FontConfig): string {
  const quote = (f: string) => (/^[\w-]+$/.test(f) && !/\s/.test(f) ? f : `"${f}"`);
  return [quote(font.family), ...font.fallback.map(quote)].join(", ");
}

export function header(s: DesignSystem, kind: "css" | "md"): string {
  const line = `${s.config.displayName} design system. Generated by ${GENERATOR} from design.config.ts.`;
  const edit = "Do not edit by hand: change design.config.ts and run `npx auto-design build`.";
  return kind === "css" ? `/* ${line}\n   ${edit} */` : `<!-- ${line} ${edit} -->`;
}
