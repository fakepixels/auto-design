import { STEPS, toCss, toHex, type Oklch, type Scale } from "../color.js";
import { SHADOW_STEPS, TYPE_STEPS } from "../scales.js";
import { ROLE_NAMES, type DesignSystem, type Mode } from "../system.js";
import { WEIGHT_NAMES } from "./shared.js";

/**
 * W3C Design Tokens (format 2025.10). Primitives live in base.tokens.json;
 * each mode file maps semantic roles onto them by alias where possible, so
 * tools that read the tokens see the same structure the CSS uses.
 */

type Token = { $type?: string; $value: unknown; $description?: string };
type Group = { [key: string]: Token | Group | string | undefined; $description?: string };

const r = (n: number, d = 4) => Math.round(n * 10 ** d) / 10 ** d;

function colorValue(c: Oklch) {
  const value: Record<string, unknown> = {
    colorSpace: "oklch",
    components: [r(c.l), r(c.c), c.c === 0 ? 0 : r(c.h, 2)],
    hex: toHex(c),
  };
  if (c.alpha !== undefined && c.alpha < 1) value.alpha = c.alpha;
  return value;
}

const colorToken = (c: Oklch): Token => ({ $type: "color", $value: colorValue(c) });
const dimension = (value: number, unit: "px" | "rem"): Token => ({ $type: "dimension", $value: { value, unit } });

function scaleGroup(scale: Scale): Group {
  const g: Group = {};
  for (const step of STEPS) g[String(step)] = colorToken(scale[step]);
  return g;
}

export function emitBaseTokens(s: DesignSystem): Group {
  const type: Group = {};
  for (const step of TYPE_STEPS) {
    const v = s.type.scale[step];
    type[step] = {
      $type: "typography",
      $value: {
        fontFamily: "{font.family.sans}",
        fontSize: { value: v.px, unit: "px" },
        lineHeight: v.lineHeight,
        letterSpacing: { value: parseFloat(v.letterSpacing), unit: "em" },
        fontWeight: 400,
      },
    };
  }

  const family: Group = {
    sans: { $type: "fontFamily", $value: [s.type.fonts.sans.family, ...s.type.fonts.sans.fallback] },
    mono: { $type: "fontFamily", $value: [s.type.fonts.mono.family, ...s.type.fonts.mono.fallback] },
  };
  if (s.type.fonts.display) {
    family.display = { $type: "fontFamily", $value: [s.type.fonts.display.family, ...s.type.fonts.display.fallback] };
  }
  const weight: Group = {};
  for (const w of s.type.weights) weight[WEIGHT_NAMES[w]!] = { $type: "fontWeight", $value: w };

  const shadow: Group = {};
  for (const step of SHADOW_STEPS) {
    const layers = s.shadows[step];
    if (!layers.length) continue;
    shadow[step] = {
      $type: "shadow",
      $value: layers.map((l) => ({
        color: { colorSpace: "oklch", components: [l.light ? 1 : 0, 0, 0], alpha: l.alpha },
        offsetX: { value: l.x, unit: "px" },
        offsetY: { value: l.y, unit: "px" },
        blur: { value: l.blur, unit: "px" },
        spread: { value: l.spread, unit: "px" },
        ...(l.inset ? { inset: true } : {}),
      })),
    };
  }

  const radiusPx = s.config.shape.radius;
  return {
    $description: `${s.config.displayName}: primitive tokens. Generated by auto-design; edit design.config.ts instead.`,
    color: {
      brand: scaleGroup(s.palettes.brand),
      neutral: scaleGroup(s.palettes.neutral),
      danger: scaleGroup(s.palettes.danger),
      success: scaleGroup(s.palettes.success),
      warning: scaleGroup(s.palettes.warning),
    },
    font: { family, weight },
    type,
    space: {
      $description: "Allowed spacing steps, as multiples of the 4px base unit.",
      unit: dimension(4, "px"),
    },
    radius: {
      sm: dimension(Math.max(0, radiusPx - 4), "px"),
      md: dimension(Math.max(0, radiusPx - 2), "px"),
      lg: dimension(radiusPx, "px"),
      xl: dimension(radiusPx + 4, "px"),
    },
    shadow,
    motion: {
      duration: {
        fast: { $type: "duration", $value: { value: s.motion.durations.fast, unit: "ms" } },
        base: { $type: "duration", $value: { value: s.motion.durations.base, unit: "ms" } },
        slow: { $type: "duration", $value: { value: s.motion.durations.slow, unit: "ms" } },
      },
      easing: {
        out: { $type: "cubicBezier", $value: [...s.motion.easing.out] },
        "in-out": { $type: "cubicBezier", $value: [...s.motion.easing.inOut] },
      },
    },
  };
}

/** Find the palette step a role color came from, for aliasing. */
function aliasFor(s: DesignSystem, c: Oklch): string | null {
  const css = toCss(c);
  for (const [name, scale] of Object.entries(s.palettes) as [string, Scale][]) {
    for (const step of STEPS) if (toCss(scale[step]) === css) return `{color.${name}.${step}}`;
  }
  return null;
}

export function emitModeTokens(s: DesignSystem, mode: Mode): Group {
  const role: Group = {};
  for (const name of ROLE_NAMES) {
    const c = s.roles[mode][name];
    const alias = c.alpha === undefined || c.alpha === 1 ? aliasFor(s, c) : null;
    role[name] = { $type: "color", $value: alias ?? colorValue(c) };
  }
  return {
    $description: `${s.config.displayName}: semantic color roles, ${mode} mode.`,
    role,
  };
}

export function emitTokens(s: DesignSystem): Record<string, string> {
  const json = (v: unknown) => JSON.stringify(v, null, 2) + "\n";
  const files: Record<string, string> = { "tokens/base.tokens.json": json(emitBaseTokens(s)) };
  const modes: Mode[] = s.config.color.modes === "both" ? ["light", "dark"] : [s.config.color.modes];
  for (const mode of modes) files[`tokens/${mode}.tokens.json`] = json(emitModeTokens(s, mode));
  return files;
}

