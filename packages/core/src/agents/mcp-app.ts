import { toCss } from "../color.js";
import type { DesignSystem, Mode } from "../system.js";

/**
 * MCP Apps: UI that renders inside a chat host's window (Claude, ChatGPT and
 * other hosts that implement the MCP Apps extension). The host passes its own
 * style variables (--color-background-*, --color-text-*, --font-sans,
 * --border-radius-* ...) and expects apps to use them for structure, so the
 * app reads as part of the conversation. The brand keeps what identifies it:
 * primary actions, focus rings, charts and imagery.
 *
 * This layer goes in auto-design.css when a system targets mcp-apps. It does
 * nothing until <html data-mcp-host> is set, which applyHostContext() does.
 */

/** Our role → the host variable that replaces it inside a host. Roles not listed keep the brand's value. */
export const HOST_ROLE_MAP: Record<string, string> = {
  background: "--color-background-primary",
  foreground: "--color-text-primary",
  card: "--color-background-primary",
  "card-foreground": "--color-text-primary",
  popover: "--color-background-primary",
  "popover-foreground": "--color-text-primary",
  secondary: "--color-background-secondary",
  "secondary-foreground": "--color-text-primary",
  muted: "--color-background-secondary",
  "muted-foreground": "--color-text-secondary",
  accent: "--color-background-secondary",
  "accent-foreground": "--color-text-primary",
  destructive: "--color-text-danger",
  "destructive-foreground": "--color-text-inverse",
  success: "--color-text-success",
  "success-foreground": "--color-text-inverse",
  warning: "--color-text-warning",
  "warning-foreground": "--color-text-inverse",
  border: "--color-border-tertiary",
  input: "--color-border-primary",
  sidebar: "--color-background-secondary",
  "sidebar-foreground": "--color-text-primary",
  "sidebar-accent": "--color-background-tertiary",
  "sidebar-accent-foreground": "--color-text-primary",
  "sidebar-border": "--color-border-tertiary",
};

const RADIUS_MAP: [string, string][] = [
  ["--radius-sm", "--border-radius-sm"],
  ["--radius-md", "--border-radius-md"],
  ["--radius-lg", "--border-radius-lg"],
  ["--radius-xl", "--border-radius-xl"],
];

function vars(s: DesignSystem, mode: Mode): string {
  const r = s.roles[mode] as Record<string, Parameters<typeof toCss>[0]>;
  const lines = Object.entries(HOST_ROLE_MAP).map(([role, host]) => `  --${role}: var(${host}, ${toCss(r[role]!)});`);
  return lines.join("\n");
}

/** The host layer for auto-design.css. Doubled selectors so it wins over the system's own role blocks. */
export function mcpLayer(s: DesignSystem, darkFirst: boolean): string {
  const base: Mode = darkFirst ? "dark" : "light";
  const other: Mode = darkFirst ? "light" : "dark";
  const otherSel = `:root:root[data-mcp-host].${other}, :root:root[data-mcp-host][data-theme="${other}"]`;
  const radii = RADIUS_MAP.map(([ours, host]) => {
    const value = s.radius[ours.replace("--radius-", "") as "sm" | "md" | "lg" | "xl"];
    return `  ${ours}: var(${host}, ${value});`;
  }).join("\n");
  return `/* Inside an MCP Apps host (Claude, ChatGPT). The host owns the canvas, text, borders and
   type; the brand keeps primary actions, focus rings and charts. Set by applyHostContext(). */
:root:root[data-mcp-host] {
  color-scheme: ${base};
${vars(s, base)}
${radii}
}
${otherSel} {
  color-scheme: ${other};
${vars(s, other)}
}
:root[data-mcp-host],
:root[data-mcp-host] body {
  background: transparent;
}`;
}

/** The lib module apps call with the host context. Framework-free; works with @modelcontextprotocol/ext-apps. */
export function mcpHostModule(s: DesignSystem): string {
  return `// @generated by auto-design from design.config.ts.
/**
 * Connect ${s.config.displayName} to an MCP Apps host (Claude, ChatGPT and others).
 *
 *   import { App } from "@modelcontextprotocol/ext-apps";
 *   import { applyHostContext } from "@/lib/mcp-host";
 *
 *   const app = new App({ name: "${s.config.name}", version: "1.0.0" });
 *   app.addEventListener("hostcontextchanged", (changed) => applyHostContext(changed));
 *   await app.connect();
 *   applyHostContext(app.getHostContext() ?? {});
 *
 * Inside a host, structure (backgrounds, text, borders, radius, type) follows the host so the
 * app reads as part of the conversation. Primary actions, focus rings and charts stay on-brand.
 * Keep <meta name="color-scheme" content="light dark"> in the page head.
 */

export interface HostContext {
  theme?: "light" | "dark";
  styles?: { variables?: Record<string, string | undefined | null>; css?: { fonts?: string } };
  safeAreaInsets?: { top?: number; right?: number; bottom?: number; left?: number };
  displayMode?: "inline" | "fullscreen" | "pip" | string;
}

export interface HostOptions {
  /** "host" (default) uses the host's typeface; "brand" keeps the system's. */
  fonts?: "host" | "brand";
}

export function applyHostContext(ctx: HostContext, options: HostOptions = {}, root: HTMLElement = document.documentElement) {
  root.setAttribute("data-mcp-host", "");
  if (ctx.theme) {
    root.dataset.theme = ctx.theme;
    root.classList.toggle("dark", ctx.theme === "dark");
    root.classList.toggle("light", ctx.theme === "light");
    root.style.colorScheme = ctx.theme;
  }
  for (const [name, value] of Object.entries(ctx.styles?.variables ?? {})) {
    if (!value || !name.startsWith("--")) continue;
    if (options.fonts === "brand" && name.startsWith("--font-") && !name.startsWith("--font-weight")) continue;
    root.style.setProperty(name, value);
  }
  const fonts = ctx.styles?.css?.fonts;
  if (fonts && options.fonts !== "brand" && !document.getElementById("mcp-host-fonts")) {
    const style = document.createElement("style");
    style.id = "mcp-host-fonts";
    style.textContent = fonts;
    document.head.appendChild(style);
  }
  const insets = ctx.safeAreaInsets;
  if (insets) {
    for (const side of ["top", "right", "bottom", "left"] as const) root.style.setProperty(\`--safe-\${side}\`, \`\${insets[side] ?? 0}px\`);
  }
  if (ctx.displayMode) root.dataset.displayMode = ctx.displayMode;
}

/** True when the page is running inside an MCP Apps host. */
export function inHost(): boolean {
  return typeof document !== "undefined" && document.documentElement.hasAttribute("data-mcp-host");
}
`;
}
