import { compile } from "@tailwindcss/node";
import { dirname } from "node:path";
import { createRequire } from "node:module";
import { describe, expect, it } from "vitest";
import { presets } from "../../presets/src/index.js";
import {
  SURFACES,
  FONTS,
  PAIRINGS,
  buildGuardrails,
  buildSystem,
  componentExamples,
  componentSources,
  contrast,
  defaultCopy,
  emitCss,
  emitDesignMd,
  findFont,
  pairingFonts,
  pairingOf,
  type DesignConfig,
} from "../src/index.js";
import { checkSource } from "../../check/src/index.js";

const require = createRequire(import.meta.url);
const tailwindDir = dirname(require.resolve("tailwindcss/package.json"));

/** Compile a system's CSS with real Tailwind and report which candidate classes exist. */
async function compiles(css: string, candidates: string[]) {
  const compiler = await compile(`@import "tailwindcss";\n${css}`, { base: tailwindDir, onDependency() {} });
  const out = compiler.build(candidates);
  const has = (c: string) => out.includes(`.${c.replace(/[:/.\[\]]/g, (m) => `\\${m}`)} {`) || out.includes(`.${c.replace(/[:/.\[\]]/g, (m) => `\\${m}`)}{`);
  return { out, has };
}

/** Class names that are markers, not utilities: they produce no CSS of their own. */
const NON_UTILITIES = new Set(["group", "peer", "dark", "light", "not-prose"]);
/** Utilities without a dash; other bare words in component strings are prop values. */
const SINGLE_WORD = new Set(["flex", "grid", "truncate", "border", "rounded", "hidden", "block", "relative", "absolute", "fixed", "underline", "uppercase", "italic", "contents", "shadow", "outline", "glass", "transition", "inline", "table", "invisible", "sticky", "isolate", "grow", "shrink"]);

describe("presets", () => {
  it("ships five distinct presets", () => {
    expect(Object.keys(presets)).toEqual(["quiet", "editorial", "glass", "terminal", "tactile"]);
    const textures = new Set(Object.values(presets).map((p) => p.texture));
    expect(textures.size).toBe(5);
    const brands = new Set(Object.values(presets).map((p) => p.color.brand));
    expect(brands.size).toBe(5);
  });

  for (const [name, preset] of Object.entries(presets)) {
    describe(name, () => {
      const s = buildSystem(preset);

      it("passes every contrast check", () => {
        expect(s.report.checks.filter((c) => !c.pass)).toEqual([]);
      });

      it("uses only open-license fonts from npm", () => {
        for (const f of [s.type.fonts.sans, s.type.fonts.mono, s.type.fonts.display]) {
          if (!f) continue;
          expect(f.license).toBe("OFL-1.1");
          expect(f.package).toMatch(/^@fontsource(-variable)?\//);
        }
      });

      it("generates components that pass its own guardrails, on every surface", () => {
        const all = buildSystem({ ...preset, surfaces: [...SURFACES] });
        const g = buildGuardrails(all);
        for (const c of componentSources(all)) {
          if (c.content) expect(checkSource(c.content, c.file, g).violations, c.file).toEqual([]);
          for (const l of c.lib ?? []) {
            if (!l.content.includes("@generated by auto-design")) expect(checkSource(l.content, l.file, g).violations, l.file).toEqual([]);
          }
        }
      });

      it("writes site examples that pass its own guardrails, for every component", () => {
        const all = buildSystem({ ...preset, surfaces: [...SURFACES] });
        const g = buildGuardrails(all);
        const examples = componentExamples(all, defaultCopy("Northwind", "Project planning for agencies"));
        const covered = new Set(examples.map((e) => e.component));
        for (const c of componentSources(all)) if (c.type !== "registry:lib") expect(covered.has(c.name), c.name).toBe(true);
        for (const e of examples) expect(checkSource(e.code, `${e.name}.tsx`, g).violations, e.name).toEqual([]);
      });

      it("uses only classes that exist in its own theme", async () => {
        const all = buildSystem({ ...preset, surfaces: [...SURFACES] });
        const classes = new Set<string>();
        const examples = componentExamples(all, defaultCopy("Northwind", "Project planning for agencies"));
        for (const c of [...componentSources(all), ...examples.map((e) => ({ content: e.code }))]) {
          for (const m of c.content.matchAll(/className=\{?(?:cn\()?"([^"]+)"|cn\(\s*"([^"]+)"|: "([^"]+)"|\? "([^"]+)"|&& "([^"]+)"/g)) {
            for (const cls of (m[1] ?? m[2] ?? m[3] ?? m[4] ?? m[5])!.split(/\s+/)) {
              if (!cls || cls.includes("${") || cls.includes("://") || /^var\(/.test(cls)) continue;
              if (/[-:/[]/.test(cls) || SINGLE_WORD.has(cls)) classes.add(cls);
            }
          }
        }
        const { out } = await compiles(emitCss(all), [...classes]);
        const escape = (c: string) => "." + c.replace(/[^a-zA-Z0-9_-]/g, (m) => `\\${m}`);
        const missing = [...classes].filter((c) => !NON_UTILITIES.has(c) && /^[a-z!\[]/.test(c) && !out.includes(escape(c)));
        expect(missing).toEqual([]);
      });

      it("compiles with Tailwind: system classes exist, defaults are gone", async () => {
        const { has } = await compiles(emitCss(s), [
          "bg-primary",
          "text-muted-foreground",
          "font-sans",
          "shadow-lg",
          "rounded-lg",
          "animate-enter",
          "bg-blue-500",
          "text-white",
          "shadow-2xl",
          "font-serif",
        ]);
        for (const c of ["bg-primary", "text-muted-foreground", "font-sans", "shadow-lg", "rounded-lg", "animate-enter"]) {
          expect(has(c), c).toBe(true);
        }
        for (const c of ["bg-blue-500", "text-white", "shadow-2xl", "font-serif"]) expect(has(c), c).toBe(false);
      });
    });
  }
});

describe("dark-first systems", () => {
  const s = buildSystem(presets.terminal!);
  const css = emitCss(s);

  it("loads dark values on :root and makes light the opt-in class", () => {
    const root = css.slice(css.indexOf(":root:root {"), css.indexOf("}", css.indexOf(":root:root {")));
    const darkBg = /--background: (oklch\([^)]+\))/.exec(root)![1];
    expect(contrast(s.roles.dark.background, { l: 0, c: 0, h: 0 })).toBeLessThan(1.5);
    expect(darkBg).toMatch(/^oklch\(0\.1/);
    expect(css).toContain(":root.light {");
    expect(css).not.toContain(":root.dark {");
    expect(css).toContain("@custom-variant dark (&:where(:root:not(.light), :root:not(.light) *));");
    expect(css).toContain("color-scheme: dark;");
  });

  it("applies dark: utilities by default", async () => {
    const { out } = await compiles(css, ["dark:bg-card"]);
    expect(out).toMatch(/:root:not\(\.light\)/);
  });

  it("tells agents how light mode works", () => {
    expect(emitDesignMd(s)).toContain('<html class="light">');
  });
});

describe("glass texture", () => {
  const s = buildSystem(presets.glass!);
  const css = emitCss(s);

  it("compiles the glass utility with a solid fallback and a frosted layer", async () => {
    const { out, has } = await compiles(css, ["glass", "bg-backdrop"]);
    expect(has("glass")).toBe(true);
    expect(has("bg-backdrop")).toBe(true);
    expect(out).toMatch(/@supports \(backdrop-filter: blur\(1px\)\) or \(-webkit-backdrop-filter: blur\(1px\)\)/);
    expect(out).toContain("-webkit-backdrop-filter: blur(24px) saturate(1.8)");
  });

  it("puts dialogs on glass and keeps cards solid", () => {
    const dialog = componentSources(s).find((c) => c.name === "dialog")!.content;
    const card = componentSources(s).find((c) => c.name === "card")!.content;
    expect(dialog).toMatch(/rounded-lg glass p-6/);
    expect(card).not.toContain("glass");
  });

  it("is absent from other textures", () => {
    expect(emitCss(buildSystem(presets.quiet!))).not.toContain("@utility glass");
  });
});

describe("font catalog", () => {
  it("builds a valid system for every pairing", () => {
    for (const p of PAIRINGS) {
      const config: DesignConfig = { ...presets.quiet!, type: { ...presets.quiet!.type, ...pairingFonts(p.id) } };
      const s = buildSystem(config);
      expect(pairingOf(config)).toBe(p.id);
      expect(s.type.weights.length).toBeGreaterThan(0);
    }
  });

  it("keeps the Google Fonts name in the stack so previews match", () => {
    const f = pairingFonts("figtree");
    expect(f.sans.family).toBe("Figtree Variable");
    expect(f.sans.fallback?.[0]).toBe("Figtree");
  });

  it("finds catalog fonts by the names sites use", () => {
    expect(findFont("Geist")?.id).toBe("geist");
    expect(findFont("'JetBrains Mono'")?.id).toBe("jetbrains-mono");
    expect(findFont("Instrument Serif Variable")?.id).toBe("instrument-serif");
    expect(findFont("Comic Sans MS")).toBeNull();
  });

  it("only lists weights the files cover", () => {
    for (const p of PAIRINGS) {
      for (const slot of [p.sans, p.mono, p.display]) {
        if (!slot) continue;
        for (const w of slot.weights) expect(FONTS[slot.font]!.available, `${p.id} ${slot.font} ${w}`).toContain(w);
      }
    }
  });
});

describe("art direction", () => {
  const IMAGES = [
    { src: "/images/photo-01.jpg", alt: "A leather tote on a stone step" },
    { src: "/images/photo-02.jpg", alt: "A wool coat on a hanger" },
    { src: "/images/photo-03.jpg", alt: "A silk scarf, folded" },
  ];
  const ART = { imagery: ["none", "supporting", "leading"], hero: ["type", "centered", "split", "full-bleed", "editorial"], grid: ["cards", "open", "editorial"], labels: ["sentence", "uppercase"], display: ["standard", "dramatic"], logo: ["mark", "wordmark"] } as const;
  const combos: Record<string, string>[] = [];
  for (const hero of ART.hero) for (const grid of ART.grid) for (const labels of ART.labels) for (const logo of ART.logo) {
    combos.push({ hero, grid, labels, logo, imagery: hero === "type" ? "none" : grid === "cards" ? "supporting" : "leading", display: labels === "uppercase" ? "dramatic" : "standard" });
  }
  const systemFor = (preset: DesignConfig, art: Record<string, string>) => buildSystem({ ...preset, surfaces: [...SURFACES], art: art as never });

  it("writes marketing blocks and examples that pass the checker in every composition, on every preset", () => {
    for (const [name, preset] of Object.entries(presets)) {
      for (const art of combos) {
        const s = systemFor(preset, art);
        const g = buildGuardrails(s);
        const label = `${name} ${JSON.stringify(art)}`;
        for (const c of componentSources(s).filter((c) => ["site-header", "hero", "collection"].includes(c.name))) {
          expect(checkSource(c.content, c.file, g).violations, `${label} ${c.file}`).toEqual([]);
        }
        for (const e of componentExamples(s, defaultCopy("Maison", "Leather goods"), IMAGES).filter((e) => ["site-header", "hero", "collection"].includes(e.component))) {
          expect(checkSource(e.code, `${e.name}.tsx`, g).violations, `${label} ${e.name}`).toEqual([]);
        }
      }
    }
  });

  it("only uses classes its theme has, whatever the composition", async () => {
    for (const art of combos.filter((_, i) => i % 6 === 0)) {
      const s = systemFor(presets.editorial!, art);
      const classes = new Set<string>();
      const blocks = componentSources(s).filter((c) => ["site-header", "hero", "collection"].includes(c.name)).map((c) => c.content);
      const examples = componentExamples(s, defaultCopy("Maison", "Leather goods"), IMAGES).filter((e) => ["site-header", "hero", "collection"].includes(e.component)).map((e) => e.code);
      for (const content of [...blocks, ...examples]) {
        for (const m of content.matchAll(/className=\{?(?:cn\()?"([^"]+)"|cn\(\s*"([^"]+)"|: "([^"]+)"|\? "([^"]+)"|&& "([^"]+)"/g)) {
          for (const cls of (m[1] ?? m[2] ?? m[3] ?? m[4] ?? m[5])!.split(/\s+/)) {
            if (!cls || cls.includes("${") || cls.includes("://") || /^var\(/.test(cls)) continue;
            if (/[-:/[]/.test(cls) || SINGLE_WORD.has(cls)) classes.add(cls);
          }
        }
      }
      const { out } = await compiles(emitCss(s), [...classes]);
      const escape = (c: string) => "." + c.replace(/[^a-zA-Z0-9_-]/g, (m) => `\\${m}`);
      const missing = [...classes].filter((c) => !NON_UTILITIES.has(c) && /^[a-z!\[]/.test(c) && !out.includes(escape(c)));
      expect(missing, JSON.stringify(art)).toEqual([]);
    }
  });

  it("captions a pictured item with its photo's name when the name is short and plain", () => {
    const s = systemFor(presets.quiet!, { imagery: "leading", hero: "full-bleed", grid: "open", labels: "uppercase", display: "dramatic", logo: "wordmark" });
    const code = (images: { src: string; alt: string }[]) => componentExamples(s, defaultCopy("Maison", "Leather goods"), images).find((e) => e.component === "collection")!.code;
    const named = code([IMAGES[0]!, { src: "/images/photo-02.jpg", alt: "Wool coat" }, { src: "/images/photo-03.jpg", alt: "Untitled" }]);
    expect(named).toContain('title: "Wool coat"');
    expect(named).not.toContain('title: "Untitled"');
    // Long descriptions stay alt text; the item keeps the copy's name.
    expect(code(IMAGES)).not.toContain('title: "A wool coat on a hanger"');
  });

  it("says how pages are composed in DESIGN.md, and keeps the defaults for systems that never chose", () => {
    const md = emitDesignMd(buildSystem({ ...presets.quiet!, art: { imagery: "leading", hero: "full-bleed", grid: "open", labels: "uppercase", display: "dramatic", logo: "wordmark" } }));
    expect(md).toContain("## Art direction");
    expect(md).toContain("Photography leads");
    expect(md).toContain("open full-bleed");
    expect(md).toContain("tracking-wordmark");
    const plain = buildSystem(presets.quiet!);
    expect(plain.config.art).toEqual({ imagery: "none", hero: "type", grid: "cards", labels: "sentence", display: "standard", logo: "mark" });
    expect(emitCss(plain)).not.toContain("--tracking-label");
  });
});
